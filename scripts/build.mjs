/**
 * Builds what HACS installs: src/index.js and everything it imports, bundled
 * into the one file named in hacs.json.
 *
 * HACS downloads a single file for a plugin, so two cards that share code can
 * only reach a dashboard as one bundle. The output is committed, because that
 * is also what HACS reads when a user tracks the default branch instead of a
 * release, and CI checks it against a fresh build.
 */

import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';

const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));

await build({
  entryPoints: ['src/index.js'],
  outfile: 'dist/bticino-intercom-card.js',
  bundle: true,
  format: 'esm',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'inline',
  // left unminified on purpose: this file is what someone reads when a call
  // fails on a wall tablet they cannot open a debugger on
  minify: false,
  banner: {
    js: `// Generated by scripts/build.mjs from src/ - do not edit.\n// bticino_ha_extras ${pkg.version}\n`,
  },
});

console.log('dist/bticino-intercom-card.js written');
